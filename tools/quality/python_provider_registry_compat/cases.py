"""Input-only scenarios for the original stateful provider registry oracle.

Every expected observation is generated by the captured original Python
classes. This module declares inputs and action sequences only.
"""

from __future__ import annotations

from dataclasses import dataclass
import json
from typing import Any


@dataclass(frozen=True)
class Action:
    """One exact original-registry or captured-host operation."""

    action_id: str
    operation: str
    payload: dict[str, Any]


@dataclass(frozen=True)
class Case:
    """An isolated profile-scoped sequence of stateful operations."""

    case_id: str
    purpose: str
    profile_id: str
    actions: tuple[Action, ...]
    initial_store_text: str | None = None


