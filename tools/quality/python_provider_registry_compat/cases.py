def record(**changes: Any) -> dict[str, Any]:
    """Return a fresh synthetic record with no real credential material."""
    value: dict[str, Any] = {
        "provider_instance_id": "connection/work",
        "adapter_id": "openai-compatible",
        "display_name": "Work connection",
        "credential_handle": "credential:synthetic-registry-key-01",
        "endpoint": "https://provider.example/v1",
        "enabled": True,
        "data_residency": "unknown",
        "health_evidence": {
            "status": "unknown",
            "observed_at": None,
            "verified": False,
        },
        "metadata": {"catalog_provider_id": "vendor"},
    }
    value.update(changes)
    return value


def host_record(**changes: Any) -> dict[str, Any]:
    """Return the host-owned public save shape without health evidence."""
    value = record(**changes)
    value.pop("health_evidence")
    return value


def action(action_id: str, operation: str, payload: dict[str, Any] | None = None) -> Action:
    """Build one action with an independent payload dictionary."""
    return Action(action_id, operation, {} if payload is None else payload)


def save(record_value: dict[str, Any], revision: int) -> Action:
    """Build a direct save call at an explicit store revision."""
    return action(
        f"save-revision-{revision}",
        "registry.save",
        {"record": record_value, "expected_revision": revision},
    )


def _store_text(
    *,
    profile_id: str = "defaults",
    version: str = "rumi.provider-registry.store.v1",
    providers: dict[str, Any] | list[Any] | None = None,
) -> str:
    """Encode a fixture-only store payload for source read-validation cases."""
    return json.dumps(
        {
            "version": version,
            "profile_id": profile_id,
            "revision": 1,
            "providers": {} if providers is None else providers,
            "migration": None,
        },
        ensure_ascii=False,
        separators=(",", ":"),
    )


