"""Generate DATA comparisons from the pinned pre-change capability factory.

This CLI imports the original runtime only on Linux GitHub Actions after all
source, output, and source-hash checks pass. Its expected values cover the
original factory's serialized target DATA only. Boundary-error examples are
marked separately and are not original-factory oracle results.
"""

import argparse
import hashlib
import importlib
import json
import os
from pathlib import Path
import sys
from typing import Any

ORACLE_COMMIT = "bf8cf14664580b7ca226b56d7bd5a311a19f44b4"
OUTPUT_FORMAT = "tobkiri.capability-projection-comparison/1"
MAX_CASE_BYTES = 4 * 1024 * 1024
MEDIA_CONTRACT = "tobkiri.service.media.inspect.v1"
CAPABILITY_ROUTE = "/api/ui/capability/invoke"
_SOURCE_HASHES = {
    "ecosystem/defaultspack/defaultspack/http_dynamic_targets.py": (
        "0e147f3a9ac3abe33ce92590b402d712c3b155c99228d91ea05169af3517f4e5"
    ),
    "ecosystem/defaultspack/defaultspack/v4_view_contract.py": (
        "8df8a3c9ddb0eda98d1573201bee22f4487baf6b69fab9b9c673afa93359f76e"
    ),
    "core_runtime/global_contracts/http_contract_dispatch.py": (
        "d8be5fe03201c7fd35169bad5914339beceadc8fea2d7a4467ed959f878e99e2"
    ),
}
_BOUNDARY_ONLY_SCOPE = "request validation only; not generated by the original factory"


def _require_ci() -> None:
    """Refuse every environment except Linux GitHub Actions."""
    if sys.platform != "linux" or os.environ.get("GITHUB_ACTIONS") != "true":
        raise ValueError("capability projection oracle is restricted to Linux GitHub Actions")


def _physical_source(source_arg: str) -> Path:
    """Require an absolute, physical original runtime directory."""
    supplied = Path(source_arg)
    if not supplied.is_absolute():
        raise ValueError("--source must be an absolute physical runtime directory")
    source = supplied.resolve(strict=True)
    if source != supplied or not source.is_dir():
        raise ValueError("--source must name an existing physical runtime directory")
    return source


def _new_output(output_arg: str, source: Path) -> Path:
    """Require a new absolute JSON file outside the source runtime tree."""
    output = Path(output_arg)
    if not output.is_absolute() or output.suffix != ".json":
        raise ValueError("--output must be an absolute .json file path")
    if output.parent.resolve(strict=True) != output.parent or not output.parent.is_dir():
        raise ValueError("--output parent must be an existing physical directory")
    if os.path.lexists(output):
        raise ValueError("--output must name a new file")
    if output == source or source in output.parents:
        raise ValueError("--output must be outside the original runtime tree")
    return output


def _verify_source_hashes(source: Path) -> dict[str, str]:
    """Verify the three original files against the fixed pre-change commit."""
    hashes: dict[str, str] = {}
    for relative, expected in _SOURCE_HASHES.items():
        path = source / relative
        if path.resolve(strict=True) != path or not path.is_file():
            raise ValueError(f"original source file is not a physical file: {relative}")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != expected:
            raise ValueError(f"original source hash differs from pinned commit: {relative}")
        hashes[relative] = digest
    return hashes


def _load_original(
    source: Path,
) -> tuple[Any, Any, Any]:
    """Import the factory and frozen DATA records only from the verified source."""
    module_names = (
        "core_runtime.global_contracts.http_contract_dispatch",
        "ecosystem.defaultspack.defaultspack.http_dynamic_targets",
    )
    if any(name in sys.modules for name in module_names):
        raise ValueError("canonical runtime modules were imported before source checks")
    sys.path.insert(0, str(source))
    dispatch = importlib.import_module(module_names[0])
    targets = importlib.import_module(module_names[1])
    expected_paths = {
        module_names[0]: source / "core_runtime/global_contracts/http_contract_dispatch.py",
        module_names[1]: source
        / "ecosystem/defaultspack/defaultspack/http_dynamic_targets.py",
        "ecosystem.defaultspack.defaultspack.v4_view_contract": source
        / "ecosystem/defaultspack/defaultspack/v4_view_contract.py",
    }
    for name, expected_path in expected_paths.items():
        module = sys.modules[name]
        if Path(module.__file__).resolve(strict=True) != expected_path:
            raise ValueError(f"canonical runtime import escaped verified source: {name}")
    return (
        targets.defaultspack_dynamic_capability_targets,
        dispatch.HTTPContractBinding,
        dispatch.HTTPContractTarget,
    )


def _json_text(value: object) -> str:
    """Serialize finite comparison DATA with stable compact formatting."""
    return json.dumps(
        value,
        ensure_ascii=True,
        allow_nan=False,
        separators=(",", ":"),
    )


def _target_data(target: Any) -> dict[str, object]:
    """Serialize every original HTTP target DATA field without normalization."""
    return {
        "contribution_id": target.contribution_id,
        "contract_id": target.contract_id,
        "operation_id": target.operation_id,
        "provider_id": target.provider_id,
        "function_id": target.function_id,
        "allowed_payload_keys": sorted(target.allowed_payload_keys),
        "owner_pack_id": target.owner_pack_id,
        "artifact_digest": target.artifact_digest,
        "input_schema": target.input_schema.decode("utf-8"),
        "read_only": target.read_only,
    }


def _binding_data(
    binding_targets: list[dict[str, str]],
    path: str,
) -> dict[str, object]:
    """Create only the three route DATA fields and five-field target records."""
    return {
        "method": "POST",
        "path": path,
        "presentation": "capability-projection-oracle",
        "targets": binding_targets,
    }


def _operation(
    *,
    operation_id: str = "inspect",
    contract_id: str = MEDIA_CONTRACT,
    provider_id: str = "provider.demo",
    function_id: str | None = "function.demo",
    input_schema: object = None,
    invokable: object = True,
    include_schema: bool = True,
) -> dict[str, object]:
    """Build one original catalog Operation with optional malformed fields."""
    operation: dict[str, object] = {
        "invokable": invokable,
        "contract_id": contract_id,
        "operation_id": operation_id,
        "provider_id": provider_id,
    }
    if function_id is not None:
        operation["function_id"] = function_id
    if include_schema:
        operation["input_schema"] = input_schema
    return operation


def _pack(
    operations: object,
    *,
    pack_id: str = "demo.pack",
    digest: str = "sha256:" + ("a" * 64),
    enabled: object = True,
    approved: object = True,
) -> dict[str, object]:
    """Build one original catalog Pack entry."""
    return {
        "pack_id": pack_id,
        "pack_artifact_digest": digest,
        "enabled": enabled,
        "approved": approved,
        "operations": operations,
    }


def _schema_with_unicode() -> dict[str, object]:
    """Return a valid object schema whose canonical bytes contain Unicode data."""
    return {
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "name": {"type": "string", "description": "名前を表示 🌱"},
            "path": {"type": "string", "description": "パス"},
        },
    }


def _make_factory_case(
    name: str,
    catalog: dict[str, object],
    factory: Any,
    binding_type: Any,
    target_type: Any,
    *,
    binding_targets: list[dict[str, str]] | None = None,
    path: str = CAPABILITY_ROUTE,
) -> dict[str, str]:
    """Generate payload and expected target DATA with the original factory."""
    envelope = {
        "binding": _binding_data(binding_targets or [], path),
        "catalog": catalog,
    }
    payload = _json_text(envelope)
    if len(payload.encode("utf-8")) > MAX_CASE_BYTES:
        raise ValueError(f"oracle payload exceeds 4 MiB: {name}")
    binding_data = envelope["binding"]
    original_binding_targets = tuple(
        target_type(
            contribution_id=item["contribution_id"],
            contract_id=item["contract_id"],
            operation_id=item["operation_id"],
            provider_id=item["provider_id"],
            function_id=item["function_id"],
        )
        for item in binding_data["targets"]
    )
    binding = binding_type(
        method=binding_data["method"],
        path=binding_data["path"],
        presentation=binding_data["presentation"],
        targets=original_binding_targets,
    )
    projected = factory(binding, catalog=catalog)
    expected = _json_text({"targets": [_target_data(target) for target in projected]})
    if len(expected.encode("utf-8")) > MAX_CASE_BYTES:
        raise ValueError(f"oracle expected output exceeds 4 MiB: {name}")
    return {"name": name, "payload": payload, "expected": expected}


def _factory_cases(factory: Any, binding_type: Any, target_type: Any) -> list[dict[str, str]]:
    """Build valid-envelope cases directly from the pinned original factory."""
    unicode_schema = _schema_with_unicode()
    bad_schema = {
        "type": "not-a-json-schema-type",
        "additionalProperties": False,
        "properties": {"name": {"type": "string"}},
    }
    external_ref_schema = {
        "type": "object",
        "additionalProperties": False,
        "properties": {"name": {"$ref": "https://example.invalid/schema.json"}},
    }
    oversized_schema = {
        "type": "object",
        "additionalProperties": False,
        "properties": {f"field_{index:02d}": {"type": "string"} for index in range(65)},
    }
    explicit_target = {
        "contribution_id": "host.captured.contribution",
        "contract_id": MEDIA_CONTRACT,
        "operation_id": "inspect",
        "provider_id": "provider.demo",
        "function_id": "function.demo",
    }

    return [
        _make_factory_case(
            "unicode_schema_bytes",
            {"packs": [_pack([_operation(input_schema=unicode_schema)])]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "no_schema_uses_media_payload_keys",
            {"packs": [_pack([_operation(include_schema=False)])]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "explicit_exact_target_suppresses_catalog_alias",
            {"packs": [_pack([_operation(input_schema=unicode_schema)])]},
            factory,
            binding_type,
            target_type,
            binding_targets=[explicit_target],
        ),
        _make_factory_case(
            "duplicate_contribution_id_rejects_all",
            {
                "packs": [
                    _pack([_operation(provider_id="provider.one")]),
                    _pack([_operation(provider_id="provider.two")]),
                ],
            },
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "invalid_schema_uses_original_fallback",
            {"packs": [_pack([_operation(input_schema=bad_schema)])]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "external_schema_reference_uses_original_fallback",
            {"packs": [_pack([_operation(input_schema=external_ref_schema)])]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "schema_with_more_than_64_properties_uses_original_fallback",
            {"packs": [_pack([_operation(input_schema=oversized_schema)])]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "approved_integer_one_is_not_true",
            {"packs": [_pack([_operation(input_schema=unicode_schema)], approved=1)]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "enabled_integer_one_is_not_true",
            {"packs": [_pack([_operation(input_schema=unicode_schema)], enabled=1)]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "invokable_integer_one_is_not_true",
            {"packs": [_pack([_operation(input_schema=unicode_schema, invokable=1)])]},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "operation_missing_provider_is_skipped",
            {
                "packs": [
                    _pack([{
                        "invokable": True,
                        "contract_id": MEDIA_CONTRACT,
                        "operation_id": "inspect",
                        "input_schema": unicode_schema,
                    }]),
                ],
            },
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "catalog_function_id_defaults_to_provider",
            {
                "packs": [
                    _pack([_operation(function_id=None, input_schema=unicode_schema)]),
                ],
            },
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "malformed_pack_and_operation_members_are_skipped",
            {
                "packs": [
                    None,
                    _pack(["not-an-operation", None]),
                ],
            },
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "malformed_catalog_packs_field_is_empty",
            {"packs": "not-a-list"},
            factory,
            binding_type,
            target_type,
        ),
        _make_factory_case(
            "different_path_returns_no_dynamic_targets",
            {"packs": [_pack([_operation(input_schema=unicode_schema)])]},
            factory,
            binding_type,
            target_type,
            path="/api/ui/other",
        ),
    ]


def _invalid_request_cases() -> list[dict[str, str]]:
    """Describe boundary-only errors; these are not original-factory results."""
    valid_envelope = {
        "binding": _binding_data([], CAPABILITY_ROUTE),
        "catalog": {"packs": []},
    }
    extra_authority = {**valid_envelope, "approved": True}
    extra_target_authority = {
        "binding": {
            **_binding_data([], CAPABILITY_ROUTE),
            "targets": [{
                "contribution_id": "x",
                "contract_id": "x",
                "operation_id": "x",
                "provider_id": "x",
                "function_id": "x",
                "approved": True,
            }],
        },
        "catalog": {"packs": []},
    }
    return [
        {
            "name": "invalid_json",
            "payload": "{",
            "expected_error": "invalid-request",
            "oracle_scope": _BOUNDARY_ONLY_SCOPE,
        },
        {
            "name": "duplicate_json_key",
            "payload": '{"binding":{},"binding":{},"catalog":{}}',
            "expected_error": "invalid-request",
            "oracle_scope": _BOUNDARY_ONLY_SCOPE,
        },
        {
            "name": "nonfinite_json_number",
            "payload": _json_text(valid_envelope)[:-1] + ',"nonfinite":NaN}',
            "expected_error": "invalid-request",
            "oracle_scope": _BOUNDARY_ONLY_SCOPE,
        },
        {
            "name": "extra_envelope_authority_field",
            "payload": _json_text(extra_authority),
            "expected_error": "invalid-request",
            "oracle_scope": _BOUNDARY_ONLY_SCOPE,
        },
        {
            "name": "extra_binding_target_authority_field",
            "payload": _json_text(extra_target_authority),
            "expected_error": "invalid-request",
            "oracle_scope": _BOUNDARY_ONLY_SCOPE,
        },
    ]


def _document(source_hashes: dict[str, str], cases: list[dict[str, str]]) -> bytes:
    """Encode the bounded cases file and enforce its aggregate transport cap."""
    for case in cases:
        for field in ("payload", "expected"):
            value = case.get(field)
            if value is not None and len(value.encode("utf-8")) > MAX_CASE_BYTES:
                raise ValueError(f"oracle case {field} exceeds 4 MiB: {case['name']}")
    document = {
        "format": OUTPUT_FORMAT,
        "oracle_commit": ORACLE_COMMIT,
        "source_files": source_hashes,
        "cases": cases,
    }
    encoded = (_json_text(document) + "\n").encode("utf-8")
    if len(encoded) > MAX_CASE_BYTES:
        raise ValueError("capability projection cases file exceeds 4 MiB")
    return encoded


def _write_new_output(output: Path, content: bytes) -> None:
    """Create the output exclusively so an existing file is never replaced."""
    with output.open("xb") as stream:
        stream.write(content)


def main(argv: list[str] | None = None) -> int:
    """Validate first, then generate comparisons using the pinned old runtime."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, help="physical original tobkiri_runtime directory")
    parser.add_argument("--output", required=True, help="new absolute cases.json path")
    args = parser.parse_args(argv)
    try:
        _require_ci()
        source = _physical_source(args.source)
        output = _new_output(args.output, source)
        source_hashes = _verify_source_hashes(source)
        factory, binding_type, target_type = _load_original(source)
        cases = _factory_cases(factory, binding_type, target_type)
        cases.extend(_invalid_request_cases())
        _write_new_output(output, _document(source_hashes, cases))
    except Exception as error:
        print(f"capability projection oracle failed: {error}", file=sys.stderr)
        return 2
    print(f"wrote capability projection DATA cases: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
