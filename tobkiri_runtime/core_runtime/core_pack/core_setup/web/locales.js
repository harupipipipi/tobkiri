  const supported = Object.freeze(Object.keys(messages));
  const normalize = (value, browserLanguage) => {
    const requested = String(value || "auto").trim().toLowerCase();
    const candidate = requested === "auto"
      ? String(browserLanguage || "ja").trim().toLowerCase()
      : requested;
    return candidate.startsWith("en") ? "en" : "ja";
  };
  const translate = (locale, key, values = {}) => {
    const template = messages[normalize(locale)][key] || messages.en[key] || key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.split(`{${name}}`).join(String(value)),
      template,
    );
  };

