"""Prove source extraction fidelity without executing bridge semantics."""

from __future__ import annotations

import ast
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/wasm/prepare_ordered_tool_bridge.py"
CHECKED_IN = ROOT / "packs/local.ai-tool-bridge-ordered-python/python"
_spec = importlib.util.spec_from_file_location("ordered_bridge_extraction", SCRIPT)
assert _spec is not None and _spec.loader is not None
_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_module)
OUTPUT_NAMES = ("original_bridge.py", "provenance.json", "inventory.json")


def _digest(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _pointer(value: object, pointer: str) -> object:
    for key in pointer.removeprefix("/").split("/"):
        value = value[int(key)] if isinstance(value, list) else value[key]
    return value


class OrderedBridgeExtractionTests(unittest.TestCase):
    """Static integrity checks runnable using only the host Python stdlib."""

    def setUp(self) -> None:
        """Isolate every preparation in its own temporary directory."""
        temporary = tempfile.TemporaryDirectory(prefix="ordered-bridge-test-")
        self.addCleanup(temporary.cleanup)
        self.output = Path(temporary.name)

    def test_checked_in_extraction_matches_original_sources(self) -> None:
        """Generated bytes and provenance cannot silently drift from source."""
        result = _module.verify(CHECKED_IN)
        self.assertFalse(result["build_performed"])
        self.assertFalse(result["production_enabled"])

    def test_every_slice_is_byte_identical_and_independently_verifiable(self) -> None:
        """Offsets, full-file hashes, line ranges, and output hashes all agree."""
        provenance = _module.prepare(self.output)
        original = (self.output / "original_bridge.py").read_bytes()
        self.assertEqual(provenance["output"]["sha256"], _digest(original))
        self.assertEqual(provenance["output"]["bytes"], len(original))
        sources = {}
        for record in provenance["sources"]:
            content = (ROOT / record["path"]).read_bytes()
            self.assertEqual(record["sha256"], _digest(content))
            self.assertEqual(record["bytes"], len(content))
            sources[record["path"]] = content
        self.assertEqual(set(sources), {_module.BRIDGE, _module.DISPATCH})
        self.assertEqual({record["symbol"] for record in provenance["slices"]}, {
            "import:__future__", "import:json", "import:re", "import:typing",
            "GlobalContractInvocationError", "_TOOL_NAME", "_invalid", "_normalize",
            "create_tool_intent_operation",
        })
        for record in provenance["slices"]:
            with self.subTest(symbol=record["symbol"]):
                source = sources[record["source_path"]]
                by_bytes = source[
                    record["source_start_byte"]:record["source_end_byte"]
                ]
                by_lines = b"".join(source.splitlines(keepends=True)[
                    record["source_start_line"] - 1:record["source_end_line"]
                ])
                extracted = original[
                    record["output_start_byte"]:record["output_end_byte"]
                ]
                extracted_lines = b"".join(original.splitlines(keepends=True)[
                    record["output_start_line"] - 1:record["output_end_line"]
                ])
                self.assertEqual(by_bytes, by_lines)
                self.assertEqual(by_lines, extracted)
                self.assertEqual(extracted, extracted_lines)
                self.assertEqual(_digest(extracted), record["sha256"])
        inventory = (self.output / "inventory.json").read_bytes()
        self.assertEqual(provenance["inventory"]["sha256"], _digest(inventory))

    def test_only_original_stdlib_imports_and_selected_definitions(self) -> None:
        """No host factory, registration shim, emulation, or host import remains."""
        _module.prepare(self.output)
        self.assertFalse(set(_module.FINALIZERS) & set(_module.SYMBOLS))
        self.assertEqual(
            (self.output / "original_bridge.py").read_bytes(),
            (CHECKED_IN / "original_bridge.py").read_bytes(),
        )
        tree = ast.parse((self.output / "original_bridge.py").read_bytes())
        imports = [node for node in ast.walk(tree)
                   if isinstance(node, (ast.Import, ast.ImportFrom))]
        self.assertEqual([
            (node.module if isinstance(node, ast.ImportFrom) else None,
             tuple(alias.name for alias in node.names)) for node in imports
        ], [
            ("__future__", ("annotations",)), (None, ("json",)), (None, ("re",)),
            ("typing", ("Any", "Callable", "Mapping")),
        ])
        definitions = [node.name for node in tree.body
                       if isinstance(node, (ast.FunctionDef, ast.ClassDef))]
        self.assertEqual(definitions, [
            "GlobalContractInvocationError", "create_tool_intent_operation",
            "_normalize", "_invalid",
        ])
        assignments = [node for node in tree.body if isinstance(node, ast.Assign)]
        self.assertEqual(len(assignments), 1)
        self.assertEqual([target.id for target in assignments[0].targets],
                         ["_TOOL_NAME"])
        forbidden = {"exec", "eval", "compile", "__import__"}
        self.assertFalse(any(
            isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
            and node.func.id in forbidden for node in ast.walk(tree)
        ))

    def test_inventory_has_three_operations_and_four_original_edges(self) -> None:
        """Operation and caller-edge evidence resolves to original manifest values."""
        _module.prepare(self.output)
        inventory = json.loads((self.output / "inventory.json").read_bytes())
        base = "rumi_ai_tool_bridge_pack.ai-tool-intent-normalize"
        self.assertEqual({item["operation_id"] for item in inventory["operations"]}, {
            base, f"{base}.generate", f"{base}.stream",
        })
        self.assertEqual({(edge["caller_function_id"], edge["operation_id"])
                          for edge in inventory["caller_edges"]}, {
            ("rumi_ai_gateway_pack.ai-gateway.generate", f"{base}.generate"),
            ("rumi_ai_gateway_pack.ai-gateway.stream", f"{base}.stream"),
            ("rumi_ai_gateway_pack.ai-gateway.text-generate", f"{base}.generate"),
            ("rumi_ai_gateway_pack.ai-gateway.messages-generate", f"{base}.generate"),
        })
        sources = {}
        for record in inventory["sources"]:
            content = (ROOT / record["path"]).read_bytes()
            self.assertEqual(_digest(content), record["sha256"])
            sources[record["path"]] = content
        for item in inventory["operations"] + inventory["caller_edges"]:
            for evidence in item["declarations"]:
                entry = _pointer(json.loads(sources[evidence["path"]]),
                                 evidence["json_pointer"])
                self.assertEqual(entry["operation_id"], item["operation_id"])
                if "caller_function_id" in item:
                    self.assertEqual(entry["caller_function_id"],
                                     item["caller_function_id"])
                    self.assertEqual(entry["target_provider_id"],
                                     item["target_provider_id"])
        for evidence in (inventory["gateway_evidence"]
                         + inventory["gateway_tool_intent_call_sites"]
                         + inventory["gateway_finalization_call_sites"]):
            content = sources[evidence["source_path"]]
            source_slice = content[
                evidence["source_start_byte"]:evidence["source_end_byte"]
            ]
            self.assertEqual(_digest(source_slice), evidence["sha256"])
        self.assertEqual([item["streaming_expression"]
                          for item in inventory["gateway_tool_intent_call_sites"]],
                         ["streaming", "True", "True"])

    def test_inventory_binds_actual_finalizer_path_and_arguments(self) -> None:
        """Evidence links the enclosing caller to both original tool paths."""
        inventory = _module._inventory()
        definitions = {
            item["symbol"]: item for item in inventory["gateway_evidence"]
        }
        self.assertTrue(
            {"_invoke", *_module.FINALIZERS} <= definitions.keys()
        )
        calls = inventory["gateway_finalization_call_sites"]
        self.assertEqual([item["symbol"] for item in calls], [
            "_finalize_stream_result", "_finalize_generate_result",
        ])
        self.assertEqual([item["positional_arguments"] for item in calls], [
            ["client", "value", "request_id", "attempt_candidate",
             "attempt_number", "attempts"],
            ["client", "value", "request_id", "attempt_candidate", "attempts"],
        ])
        self.assertEqual([item["keyword_arguments"] for item in calls], [
            [{"name": "packvm_response", "expression": "packvm_response"}],
            [{"name": "streaming", "expression": "streaming"},
             {"name": "packvm_response", "expression": "packvm_response"}],
        ])
        source = (ROOT / _module.GATEWAY).read_bytes()
        tree = ast.parse(source)
        functions = {
            node.name: node for node in tree.body
            if isinstance(node, ast.FunctionDef)
        }
        for item in calls:
            self.assertEqual(item["caller_symbol"], "_invoke")
            self.assertTrue(
                definitions["_invoke"]["source_start_line"]
                <= item["source_start_line"] <= item["source_end_line"]
                <= definitions["_invoke"]["source_end_line"]
            )
            selected = source[item["source_start_byte"]:item["source_end_byte"]]
            self.assertEqual(selected, b"".join(source.splitlines(keepends=True)[
                item["source_start_line"] - 1:item["source_end_line"]
            ]))
            self.assertEqual(_digest(selected), item["sha256"])
            self.assertEqual(_module._source_slice(
                _module.GATEWAY, source, functions[item["symbol"]], item["symbol"],
            )[1], definitions[item["symbol"]])
        for item, owner in zip(inventory["gateway_tool_intent_call_sites"], (
            "_finalize_generate_result", "_finalize_stream_result",
            "_attach_stream_tool_intents",
        )):
            self.assertTrue(
                definitions[owner]["source_start_line"]
                <= item["source_start_line"] <= item["source_end_line"]
                <= definitions[owner]["source_end_line"]
            )
        downstream = {
            "_finalize_generate_result": [
                ("_tool_intents", ["client", 'result["tool_intents"]', "request_id"],
                 [("streaming", "streaming")]),
            ],
            "_finalize_stream_result": [
                ("_attach_stream_tool_intents",
                 ["client", "events", "request_id"], []),
                ("_tool_intents",
                 ["client", 'value.get("tool_intents", [])', "request_id"],
                 [("streaming", "True")]),
            ],
            "_attach_stream_tool_intents": [
                ("_tool_intents", ["client", "[intent]", "request_id"],
                 [("streaming", "True")]),
            ],
        }
        for owner, expected in downstream.items():
            nodes = sorted((
                node for node in ast.walk(functions[owner])
                if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id in {"_tool_intents", "_attach_stream_tool_intents"}
            ), key=lambda node: node.lineno)
            self.assertEqual([(
                node.func.id,
                [ast.get_source_segment(source.decode(), item) for item in node.args],
                [(item.arg, ast.get_source_segment(source.decode(), item.value))
                 for item in node.keywords],
            ) for node in nodes], expected)

    def test_changed_finalizer_call_path_is_rejected(self) -> None:
        """Unrelated references cannot replace missing, duplicated or changed edges."""
        capture = _module._capture
        source = capture(_module.GATEWAY)
        for mutation in (
            "missing", "duplicate", "identity", "candidate", "attempt", "streaming",
            "packvm_response", "outside_invoke", "nested_invoke",
        ):
            if mutation in {"missing", "outside_invoke", "nested_invoke"}:
                changed = source.replace(
                    b"return _finalize_generate_result(",
                    b"return unrelated_generate_result(", 1,
                )
                if mutation == "outside_invoke":
                    changed += (
                        b"\ndef unrelated_finalizer_reference():\n"
                        b"    return _finalize_generate_result(\n"
                        b"        client, value, request_id, "
                        b"attempt_candidate, attempts,\n"
                        b"        streaming=streaming, "
                        b"packvm_response=packvm_response)\n"
                    )
                elif mutation == "nested_invoke":
                    changed = changed.replace(
                        b"    resolve_only = bool(payload.get(\"resolve_only\"))",
                        b"    def unrelated_finalizer_reference():\n"
                        b"        return _finalize_generate_result(\n"
                        b"            client, value, request_id, "
                        b"attempt_candidate, attempts,\n"
                        b"            streaming=streaming, "
                        b"packvm_response=packvm_response)\n"
                        b"    resolve_only = bool(payload.get(\"resolve_only\"))", 1,
                    )
            elif mutation == "duplicate":
                changed = source.replace(
                    b"                return _finalize_stream_result(",
                    b"                _finalize_stream_result()\n"
                    b"                return _finalize_stream_result(", 1,
                )
            elif mutation == "identity":
                changed = source.replace(
                    b"return _finalize_stream_result(",
                    b"return _finalize_generate_result(", 1,
                )
            else:
                tree = ast.parse(source)
                target = (
                    "_finalize_generate_result"
                    if mutation in {"candidate", "streaming"}
                    else "_finalize_stream_result"
                )
                call = next(
                    node for node in ast.walk(_module._symbol(tree, "_invoke"))
                    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                    and node.func.id == target
                )
                expression = ast.get_source_segment(source.decode(), call).encode()
                before, after = {
                    "candidate": (b"attempt_candidate", b"selected"),
                    "attempt": (b"attempt_number", b"1"),
                    "streaming": (b"streaming=streaming", b"streaming=False"),
                    "packvm_response": (
                        b"packvm_response=packvm_response", b"packvm_response=False",
                    ),
                }[mutation]
                changed = source.replace(
                    expression, expression.replace(before, after, 1), 1,
                )
            with self.subTest(mutation=mutation):
                self.assertNotEqual(changed, source)
                with patch.object(_module, "_capture", lambda path: (
                    changed if path == _module.GATEWAY else capture(path)
                )):
                    with self.assertRaisesRegex(ValueError, "finalization"):
                        _module._inventory()

    def test_deterministic_preparation_does_not_change_originals(self) -> None:
        """Output directory is not evidence, and source files remain untouched."""
        paths = [_module.BRIDGE, _module.DISPATCH, _module.GATEWAY]
        before = {path: (ROOT / path).read_bytes() for path in paths}
        first, second = self.output / "one", self.output / "two"
        self.assertEqual(_module.prepare(first), _module.prepare(second))
        for name in OUTPUT_NAMES:
            self.assertEqual((first / name).read_bytes(), (second / name).read_bytes())
        self.assertEqual(before, {path: (ROOT / path).read_bytes() for path in paths})

    def test_wrapper_source_and_actual_delegation_sites_are_bound(self) -> None:
        """Profile edge names alone do not pin wrapper implementation bytes."""
        _module.prepare(self.output)
        inventory = json.loads((self.output / "inventory.json").read_bytes())
        wrappers = inventory["wrapper_evidence"]
        self.assertEqual({item["caller_function_id"] for item in wrappers}, {
            "rumi_ai_gateway_pack.ai-gateway.text-generate",
            "rumi_ai_gateway_pack.ai-gateway.messages-generate",
        })
        for wrapper in wrappers:
            self.assertEqual([item["symbol"] for item in
                              wrapper["gateway_delegation_calls"]],
                             ["gateway.create_generate_operation", "generate"])
            evidence = wrapper["definitions"] + wrapper["gateway_delegation_calls"]
            for item in evidence:
                source = (ROOT / item["source_path"]).read_bytes()
                self.assertEqual(_digest(source[
                    item["source_start_byte"]:item["source_end_byte"]
                ]), item["sha256"])

    def test_changed_wrapper_source_invalidates_inventory(self) -> None:
        """Even an unselected wrapper change invalidates full source identity."""
        from unittest.mock import patch
        _module.prepare(self.output)
        capture = _module._capture
        for filename, _ in _module.WRAPPERS.values():
            def changed(path, filename=filename):
                content = capture(path)
                if path.endswith(filename):
                    content += b"\n# changed wrapper\n"
                return content
            with self.subTest(wrapper=filename), patch.object(
                _module, "_capture", changed,
            ):
                with self.assertRaisesRegex(ValueError, "inventory.json"):
                    _module.verify(self.output)

    def test_wrapper_identity_cannot_disagree_with_profile_edge(self) -> None:
        """Fresh preparation must not relabel a different implementation as a caller."""
        from unittest.mock import patch
        capture = _module._capture
        def changed(path):
            content = capture(path)
            if path.endswith("/text_generate.py"):
                content = content.replace(
                    b'FUNCTION_ID = "rumi_ai_gateway_pack.ai-gateway.text-generate"',
                    b'FUNCTION_ID = "other.caller"',
                )
            return content
        with patch.object(_module, "_capture", changed):
            with self.assertRaisesRegex(ValueError, "wrapper identity"):
                _module.prepare(self.output)

    def test_verification_rejects_tampering_without_rewriting(self) -> None:
        """Verification detects changed code or evidence and is strictly read-only."""
        for name in OUTPUT_NAMES:
            with self.subTest(name=name):
                _module.prepare(self.output)
                target = self.output / name
                tampered = target.read_bytes() + b"\n"
                target.write_bytes(tampered)
                with self.assertRaisesRegex(ValueError, name):
                    _module.verify(self.output)
                self.assertEqual(target.read_bytes(), tampered)

    def test_verification_rejects_changed_source_outside_extracted_slices(self) -> None:
        """Whole original-file hashes also bind omitted host-provider source."""
        _module.prepare(self.output)
        capture = _module._capture

        def changed_capture(path: str) -> bytes:
            content = capture(path)
            if path == _module.BRIDGE:
                content += b"\n# An unselected source line changed.\n"
            return content

        with patch.object(_module, "_capture", changed_capture):
            with self.assertRaisesRegex(ValueError, "provenance.json"):
                _module.verify(self.output)

    def test_verification_does_not_create_missing_output(self) -> None:
        """A verification request cannot accidentally perform preparation."""
        output = self.output / "missing"
        with self.assertRaisesRegex(ValueError, "original_bridge.py"):
            _module.verify(output)
        self.assertFalse(output.exists())

    def test_preparation_rejects_non_regular_outputs(self) -> None:
        """Preparation cannot follow an output symlink and overwrite its target."""
        for kind in ("output_file", "output_symlink", "module_symlink"):
            with self.subTest(kind=kind):
                output = self.output / kind
                target = self.output / f"{kind}_target"
                if kind == "output_file":
                    output.write_bytes(b"untouched")
                elif kind == "output_symlink":
                    target.mkdir()
                    output.symlink_to(target, target_is_directory=True)
                else:
                    output.mkdir()
                    target.write_bytes(b"untouched")
                    (output / "original_bridge.py").symlink_to(target)
                with self.assertRaisesRegex(ValueError, "output must"):
                    _module.prepare(output)
                if kind == "output_file":
                    self.assertEqual(output.read_bytes(), b"untouched")
                elif kind == "module_symlink":
                    self.assertEqual(target.read_bytes(), b"untouched")

    def test_cli_prepares_and_verifies_only_source_files(self) -> None:
        """The CLI runs preparation only, not bridge code or a compiler."""
        for options in ([], ["--verify"]):
            result = subprocess.run(
                [sys.executable, str(SCRIPT), "--output", str(self.output), *options],
                capture_output=True, text=True, check=False,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertFalse(json.loads(result.stdout)["build_performed"])
        self.assertEqual(
            {path.name for path in self.output.iterdir()}, set(OUTPUT_NAMES),
        )


if __name__ == "__main__":
    unittest.main()
