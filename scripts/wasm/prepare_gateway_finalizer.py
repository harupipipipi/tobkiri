def _extract(sources: dict[str, bytes]) -> tuple[bytes, dict[str, Any]]:
    trees = {path: ast.parse(sources[path], filename=path)
             for path in (GATEWAY, DISPATCH, LIFECYCLE)}
    selected = []
    for module, names in (
        ("__future__", ("annotations",)), ("dataclasses", ("dataclass",)),
        ("typing", ("Any", "Iterable", "Mapping")),
    ):
        matches = [node for node in trees[GATEWAY].body
                   if isinstance(node, ast.ImportFrom) and node.module == module
                   and node.level == 0
                   and tuple(alias.name for alias in node.names) == names
                   and not any(alias.asname for alias in node.names)]
        if len(matches) != 1:
            raise ValueError(f"unexpected original stdlib import: {module}")
        selected.append((GATEWAY, matches[0], f"import:{module}"))
    selected.append((DISPATCH, _symbol(
        trees[DISPATCH], "GlobalContractInvocationError",
    ), "GlobalContractInvocationError"))
    selected.extend((LIFECYCLE, _symbol(trees[LIFECYCLE], name), name)
                    for name in TASK_STATE_SYMBOLS)
    selected.extend((GATEWAY, _symbol(trees[GATEWAY], name), name)
                    for name in (*SYMBOLS, *REWRITES))
    output = bytearray(HEADER)
    records, rewrites = [], []
    for index, (path, node, name) in enumerate(selected):
        before, record = _slice(path, sources[path], node, name)
        value = before
        if name in REWRITES:
            if _sha256(before) != REWRITE_SOURCE_SHA256[name]:
                raise ValueError(f"unreviewed rewrite source changed: {name}")
            value = REWRITES[name]
            record.update({
                "reason": REWRITE_REASONS[name],
                "before_text": before.decode(), "after_text": value.decode(),
                "after_sha256": _sha256(value),
            })
        record.update(output_start_byte=len(output),
                      output_start_line=output.count(b"\n") + 1)
        output.extend(value)
        record.update(output_end_byte=len(output), output_end_line=(
            output.count(b"\n") + (not value.endswith(b"\n"))
        ))
        if index + 1 < len(selected):
            output.extend(b"\n\n")
        (rewrites if name in REWRITES else records).append(record)
    content = bytes(output)
    ast.parse(content, filename="original_gateway_finalizer.py")
    return content, {
        "schema": "io.tobkiri.gateway-finalizer-extraction.v1",
        "generator": "scripts/wasm/prepare_gateway_finalizer.py",
        "extraction": "verbatim-complete-source-lines-with-explicit-rewrites",
        "line_numbers": "one-based-inclusive",
        "byte_offsets": "zero-based-half-open",
        "sources": [_record(path, sources[path])
                    for path in (GATEWAY, DISPATCH, LIFECYCLE)],
        "slices": records, "rewrites": rewrites,
        "output": _record("original_gateway_finalizer.py", content),
        "build_performed": False, "production_enabled": False,
    }


def _strict_json(content: bytes) -> Any:
    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError("duplicate evidence key")
            result[key] = value
        return result

    def reject(value: str) -> None:
        raise ValueError(f"nonfinite evidence number: {value}")

    return json.loads(content, object_pairs_hook=pairs, parse_constant=reject)


def _inventory(sources: dict[str, bytes]) -> dict[str, Any]:
    edges: dict[tuple[str, str, str, str], dict[str, Any]] = {}
    for path in (PROFILE, INTENT):
        document = _strict_json(sources[path])
        for index, edge in enumerate(document["requested_edges"]):
            if edge["contract_id"] not in DEPENDENCIES:
                continue
            key = (edge["caller_function_id"], edge["contract_id"],
                   edge["operation_id"], edge["target_provider_id"])
            item = edges.setdefault(key, {
                "caller_function_id": key[0], "contract_id": key[1],
                "operation_id": key[2], "target_provider_id": key[3],
                "declarations": [],
            })
            item["declarations"].append({
                "path": path, "json_pointer": f"/requested_edges/{index}",
            })
    expected = set()
    for contract, prefix in DEPENDENCIES.items():
        for name, suffix in (("generate", "generate"), ("stream", "stream"),
                             ("text-generate", "generate"),
                             ("messages-generate", "generate")):
            stream_only = contract == "tobkiri.service.ai.stream.normalize.v1"
            if stream_only and name != "stream":
                continue
            expected.add((f"rumi_ai_gateway_pack.ai-gateway.{name}", contract,
                          prefix if stream_only else f"{prefix}.{suffix}",
                          PROVIDER_IDS[contract]))
    if (set(edges) != expected or len(edges) != 9
            or any(len(edge["declarations"]) != 2 for edge in edges.values())):
        raise ValueError("expected original nine finalization dependency edges")
    tree = ast.parse(sources[GATEWAY], filename=GATEWAY)
    invoke = _symbol(tree, "_invoke")
    calls = []
    for node in ast.walk(invoke):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id in ("_finalize_generate_result",
                                     "_finalize_stream_result")):
            calls.append(_slice(GATEWAY, sources[GATEWAY], node, node.func.id)[1])
    if sorted(call["symbol"] for call in calls) != [
        "_finalize_generate_result", "_finalize_stream_result",
    ]:
        raise ValueError("production must call both reviewed finalization seams")
    return {
        "schema": "io.tobkiri.gateway-finalizer-inventory.v1",
        "sources": [_record(path, content) for path, content in sources.items()],
        "caller_edges": list(edges.values()),
        "production_seam_calls": sorted(
            calls, key=lambda item: item["source_start_line"],
        ),
        "exported_helper_operations": ["generate", "stream"],
        "exported_interface": "local:ai-gateway-finalizer-python/finalizer@1.0.0",
        "required_interfaces": [
            "local:ai-gateway-tool-caller-python/caller@1.0.0",
            "local:ai-usage-cost-python/usage-cost@1.0.0",
            "local:ai-stream-normalizer-python/stream-normalizer@1.0.0",
        ],
        "not_migrated": [
            "_invoke", "provider generation", "routing", "credential handling",
            "retry and failover", "Host capture", "PackVM response serialization",
            "text-generate wrapper", "messages-generate wrapper",
            "production registration and activation",
        ],
        "notes": [
            "Recorded Candidate and provider result are DATA, not authority.",
            "Only ordinary packvm_response=False is admitted by the new boundary.",
            "Source domain rejection and imported Core errors remain disjoint.",
            "Every imported Core error is terminal and retains exact code/message.",
            "Event loops preserve original ordering and partial mutation locally.",
            "No partial successful response is exposed after an imported error.",
            "Source doubles do not prove guest execution, composition, or Gate.",
            "Codec and dependency WIT are hash-bound staged references, not copies.",
        ],
    }


def _prepared_files() -> tuple[dict[str, bytes], dict[str, Any]]:
    paths = (
        GATEWAY, DISPATCH, LIFECYCLE, PROFILE, INTENT,
        *CODEC_PATHS, CORE_WIT, *DEPENDENCY_WIT, TRANSITIVE_WIT,
        *DEPENDENCY_SOURCES,
    )
    sources = {path: _capture(path) for path in paths}
    module, provenance = _extract(sources)
    inventory = _json_bytes(_inventory(sources))
    provenance["inventory"] = _record("inventory.json", inventory)
    provenance["transport_dependencies"] = [
        _record(path, sources[path])
        for path in (*CODEC_PATHS, CORE_WIT, *DEPENDENCY_WIT, TRANSITIVE_WIT,
                     *DEPENDENCY_SOURCES)
    ]
    provenance["protocol"] = "ordered-finite-json-v2"
    return {
        "original_gateway_finalizer.py": module,
        "inventory.json": inventory, "provenance.json": _json_bytes(provenance),
    }, provenance

def prepare(output: Path) -> dict[str, Any]:
    """Write deterministic slices with no link-following, compiler, or runtime."""
    files, provenance = _prepared_files()
    descriptor = None
    try:
        descriptor = _directory(Path(output), create=True)
        # Preflight every existing target before changing any file.
        for name in files:
            try:
                info = os.stat(name, dir_fd=descriptor, follow_symlinks=False)
            except FileNotFoundError:
                continue
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise ValueError(f"output must be an unlinked regular file: {name}")
        for name, content in files.items():
            target = os.open(
                name, os.O_WRONLY | os.O_CREAT | os.O_NOFOLLOW | os.O_NONBLOCK,
                0o644, dir_fd=descriptor,
            )
            try:
                info = os.fstat(target)
                if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                    raise ValueError(f"unsafe output target: {name}")
                os.ftruncate(target, 0)
                remaining = memoryview(content)
                while remaining:
                    written = os.write(target, remaining)
                    if not written:
                        raise ValueError(f"incomplete output write: {name}")
                    remaining = remaining[written:]
            finally:
                os.close(target)
    except OSError as error:
        raise ValueError("output must have only real directory ancestors") from error
    finally:
        if descriptor is not None:
            os.close(descriptor)
    return provenance


def verify(output: Path) -> dict[str, Any]:
    """Verify all captured source and transport evidence without rewriting it."""
    files, provenance = _prepared_files()
    for name, expected in files.items():
        if bounded_read(Path(output) / name) != expected:
            raise ValueError(f"extraction does not match original source: {name}")
    return provenance


def main() -> None:
    """Prepare or verify source evidence, never a component or deployment."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    result = verify(args.output) if args.verify else prepare(args.output)
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
