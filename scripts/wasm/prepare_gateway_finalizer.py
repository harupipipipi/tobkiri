def _sha256(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def _directory(path: Path, *, create: bool = False) -> int:
    """Open every directory component without following any symbolic link."""
    if ".." in path.parts:
        raise ValueError("parent traversal is not allowed")
    path = Path(os.path.abspath(path)) if not path.is_absolute() else path
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    descriptor = os.open(path.anchor, flags)
    try:
        for part in path.parts[1:]:
            if create:
                try:
                    os.mkdir(part, dir_fd=descriptor)
                except FileExistsError:
                    pass
            child = os.open(part, flags, dir_fd=descriptor)
            os.close(descriptor)
            descriptor = child
        return descriptor
    except BaseException:
        os.close(descriptor)
        raise


def bounded_read(path: Path, limit: int = MAX_SOURCE_BYTES) -> bytes:
    """Read a stable regular file, capped before and during the read."""
    path = Path(path)
    if ".." in path.parts:
        raise ValueError("parent traversal is not allowed")
    descriptor = parent = None
    try:
        parent = _directory(path.parent)
        descriptor = os.open(
            path.name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
            dir_fd=parent,
        )
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode) or before.st_size > limit:
            raise ValueError(f"source must be a bounded regular file: {path}")
        chunks = []
        remaining = limit + 1
        while remaining:
            chunk = os.read(descriptor, min(remaining, 64 * 1024))
            if not chunk:
                break
            chunks.append(chunk)
            remaining -= len(chunk)
        content = b"".join(chunks)
        after = os.fstat(descriptor)
        identity = lambda item: (item.st_dev, item.st_ino, item.st_size,
                                 item.st_mtime_ns, item.st_ctime_ns)
        if (len(content) > limit or len(content) != before.st_size
                or identity(before) != identity(after)):
            raise ValueError(f"source changed or exceeded read bound: {path}")
        return content
    except OSError as error:
        raise ValueError(f"unsafe or missing regular file: {path}") from error
    finally:
        if descriptor is not None:
            os.close(descriptor)
        if parent is not None:
            os.close(parent)


def _capture(path: str) -> bytes:
    relative = Path(path)
    if relative.is_absolute() or ".." in relative.parts:
        raise ValueError("source path must be relative and contained")
    return bounded_read(ROOT / relative)


def _record(path: str, content: bytes) -> dict[str, Any]:
    return {"path": path, "sha256": _sha256(content), "bytes": len(content)}


def _symbol(tree: ast.Module, name: str) -> ast.stmt:
    matches = [node for node in tree.body if (
        isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name
    ) or (
        isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name
            for target in node.targets
        )
    )]
    if len(matches) != 1:
        raise ValueError(f"expected exactly one source definition of {name}")
    return matches[0]


def _slice(
    path: str, content: bytes, node: ast.AST, label: str,
) -> tuple[bytes, dict[str, Any]]:
    start = node.lineno
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.decorator_list:
        start = min(start, *(item.lineno for item in node.decorator_list))
    end = node.end_lineno
    if end is None:
        raise ValueError(f"missing source extent for {label}")
    lines = content.splitlines(keepends=True)
    begin, finish = sum(map(len, lines[:start - 1])), sum(map(len, lines[:end]))
    value = content[begin:finish]
    return value, {
        "symbol": label, "source_path": path,
        "source_start_line": start, "source_end_line": end,
        "source_start_byte": begin, "source_end_byte": finish,
        "sha256": _sha256(value),
    }



