"""Extract only original Gateway tool callers; never build or activate a Pack.

Each selected complete source line is retained byte for byte. Reads and writes
walk directory descriptors without following symlinks, including ancestor links.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
from pathlib import Path
import stat
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
ECOSYSTEM = "tobkiri_runtime/ecosystem"
GATEWAY = f"{ECOSYSTEM}/rumi_ai_gateway_pack/runtime/gateway.py"
DISPATCH = "tobkiri_runtime/core_runtime/global_contract_dispatch.py"
BRIDGE_PACK = f"{ECOSYSTEM}/rumi_ai_tool_bridge_pack"
PROFILE = f"{ECOSYSTEM}/defaultspack/v4/defaults.profile.v5.json"
INTENT = f"{ECOSYSTEM}/defaultspack/v4/defaults.profile.intent.v1.json"
CODEC_PACK = "packs/local.ai-tool-bridge-ordered-python"
CODEC_PATHS = tuple(f"{CODEC_PACK}/{name}" for name in (
    "ordered_json.py", "ordered_json_v2.py",
))
CORE_WIT = "crates/tobkiri-wit/wit/core/core.wit"
BRIDGE_WIT = f"{CODEC_PACK}/wit/pack-v2.wit"
CONTRACT = "tobkiri.service.ai.tool_intent.normalize.v1"
PREFIX = "rumi_ai_tool_bridge_pack.ai-tool-intent-normalize"
WRAPPERS = {
    "text-generate": ("text_generate.py", "create_text_generate_operation"),
    "messages-generate": (
        "messages_generate.py", "create_messages_generate_operation",
    ),
}
SYMBOLS = (
    "TOOL_BRIDGE_CONTRACT", "TOOL_BRIDGE_GENERATE_OPERATION",
    "TOOL_BRIDGE_STREAM_OPERATION", "TOOL_BRIDGE_OPERATION",
    "_attach_stream_tool_intents", "_tool_intents",
)
MAX_SOURCE_BYTES = 8 * 1024 * 1024
HEADER = (
    b"# Generated by scripts/wasm/prepare_gateway_tool_caller.py.\n"
    b"# Verbatim source slices only; see provenance.json.\n"
    b"# GlobalContractClient annotations are postponed, not authority stubs.\n\n"
)


def _sha256(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def _directory(path: Path, *, create: bool = False) -> int:
    """Open every directory component without following any symbolic link."""
    if ".." in path.parts:
        raise ValueError("parent traversal is not allowed")
    path = Path(os.path.abspath(path)) if not path.is_absolute() else path
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    descriptor = os.open(path.anchor, flags)
    try:
        for part in path.parts[1:]:
            if create:
                try:
                    os.mkdir(part, dir_fd=descriptor)
                except FileExistsError:
                    pass
            child = os.open(part, flags, dir_fd=descriptor)
            os.close(descriptor)
            descriptor = child
        return descriptor
    except BaseException:
        os.close(descriptor)
        raise


def bounded_read(path: Path, limit: int = MAX_SOURCE_BYTES) -> bytes:
    """Read a stable regular file, capped before and during the read."""
    path = Path(path)
    if ".." in path.parts:
        raise ValueError("parent traversal is not allowed")
    descriptor = parent = None
    try:
        parent = _directory(path.parent)
        descriptor = os.open(
            path.name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
            dir_fd=parent,
        )
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode) or before.st_size > limit:
            raise ValueError(f"source must be a bounded regular file: {path}")
        chunks = []
        remaining = limit + 1
        while remaining:
            chunk = os.read(descriptor, min(remaining, 64 * 1024))
            if not chunk:
                break
            chunks.append(chunk)
            remaining -= len(chunk)
        content = b"".join(chunks)
        after = os.fstat(descriptor)
        identity = lambda item: (item.st_dev, item.st_ino, item.st_size,
                                 item.st_mtime_ns, item.st_ctime_ns)
        if (len(content) > limit or len(content) != before.st_size
                or identity(before) != identity(after)):
            raise ValueError(f"source changed or exceeded read bound: {path}")
        return content
    except OSError as error:
        raise ValueError(f"unsafe or missing regular file: {path}") from error
    finally:
        if descriptor is not None:
            os.close(descriptor)
        if parent is not None:
            os.close(parent)


def _capture(path: str) -> bytes:
    relative = Path(path)
    if relative.is_absolute() or ".." in relative.parts:
        raise ValueError("source path must be relative and contained")
    return bounded_read(ROOT / relative)


def _record(path: str, content: bytes) -> dict[str, Any]:
    return {"path": path, "sha256": _sha256(content), "bytes": len(content)}


def _symbol(tree: ast.Module, name: str) -> ast.stmt:
    matches = [node for node in tree.body if (
        isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name
    ) or (
        isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name
            for target in node.targets
        )
    )]
    if len(matches) != 1:
        raise ValueError(f"expected exactly one source definition of {name}")
    return matches[0]


def _slice(
    path: str, content: bytes, node: ast.AST, label: str,
) -> tuple[bytes, dict[str, Any]]:
    start = node.lineno
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.decorator_list:
        start = min(start, *(item.lineno for item in node.decorator_list))
    end = node.end_lineno
    if end is None:
        raise ValueError(f"missing source extent for {label}")
    lines = content.splitlines(keepends=True)
    begin, finish = sum(map(len, lines[:start - 1])), sum(map(len, lines[:end]))
    value = content[begin:finish]
    return value, {
        "symbol": label, "source_path": path,
        "source_start_line": start, "source_end_line": end,
        "source_start_byte": begin, "source_end_byte": finish,
        "sha256": _sha256(value),
    }


def _extract(sources: dict[str, bytes]) -> tuple[bytes, dict[str, Any]]:
    trees = {path: ast.parse(sources[path], filename=path)
             for path in (GATEWAY, DISPATCH)}
    selected = []
    for module, names in (
        ("__future__", ("annotations",)), ("typing", ("Any", "Iterable", "Mapping")),
    ):
        matches = [node for node in trees[GATEWAY].body
                   if isinstance(node, ast.ImportFrom) and node.module == module
                   and node.level == 0
                   and tuple(alias.name for alias in node.names) == names
                   and not any(alias.asname for alias in node.names)]
        if len(matches) != 1:
            raise ValueError(f"unexpected original stdlib import: {module}")
        selected.append((GATEWAY, matches[0], f"import:{module}"))
    selected.append((DISPATCH, _symbol(
        trees[DISPATCH], "GlobalContractInvocationError",
    ), "GlobalContractInvocationError"))
    selected.extend((GATEWAY, _symbol(trees[GATEWAY], name), name)
                    for name in SYMBOLS)
    output = bytearray(HEADER)
    records = []
    for path, node, name in selected:
        value, record = _slice(path, sources[path], node, name)
        record.update(output_start_byte=len(output),
                      output_start_line=output.count(b"\n") + 1)
        output.extend(value)
        record.update(output_end_byte=len(output), output_end_line=(
            output.count(b"\n") + (not value.endswith(b"\n"))
        ))
        output.extend(b"\n\n")
        records.append(record)
    content = bytes(output)
    ast.parse(content, filename="original_gateway_tool_caller.py")
    return content, {
        "schema": "io.tobkiri.gateway-tool-caller-extraction.v1",
        "generator": "scripts/wasm/prepare_gateway_tool_caller.py",
        "extraction": "verbatim-complete-source-lines",
        "line_numbers": "one-based-inclusive",
        "byte_offsets": "zero-based-half-open",
        "sources": [_record(path, sources[path]) for path in (GATEWAY, DISPATCH)],
        "slices": records,
        "output": _record("original_gateway_tool_caller.py", content),
        "build_performed": False, "production_enabled": False,
    }


def _strict_json(content: bytes) -> Any:
    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError("duplicate evidence key")
            result[key] = value
        return result

    def reject(value: str) -> None:
        raise ValueError(f"nonfinite evidence number: {value}")

    return json.loads(content, object_pairs_hook=pairs, parse_constant=reject)


def _inventory(sources: dict[str, bytes]) -> dict[str, Any]:
    documents = {path: _strict_json(content) for path, content in sources.items()
                 if path.endswith(".json")}
    declarations: dict[str, list[dict[str, str]]] = {}
    for path, document in documents.items():
        if path.endswith("/contracts.v4.json"):
            for index, contract in enumerate(document["contracts"]):
                if contract["contract_id"] == CONTRACT:
                    for position, operation in enumerate(contract["operations"]):
                        declarations.setdefault(operation["operation_id"], []).append({
                            "path": path,
                            "json_pointer": f"/contracts/{index}/operations/{position}",
                        })
        elif path.endswith("/executables.v4.json"):
            for index, variant in enumerate(document["variants"]):
                for position, operation in enumerate(variant["operations"]):
                    if operation["contract_id"] == CONTRACT:
                        declarations.setdefault(operation["operation_id"], []).append({
                            "path": path,
                            "json_pointer": f"/variants/{index}/operations/{position}",
                        })
        elif path.endswith("/pack.v4.json"):
            for index, operation in enumerate(document["operation_catalog"]):
                if operation["contract_reference"] == CONTRACT:
                    declarations.setdefault(operation["operation_id"], []).append({
                        "path": path, "json_pointer": f"/operation_catalog/{index}",
                    })
    if set(declarations) != {PREFIX, f"{PREFIX}.generate", f"{PREFIX}.stream"} or any(
        len(refs) != 3 for refs in declarations.values()
    ):
        raise ValueError("expected three bridge operations in three manifests")
    edges: dict[tuple[str, str, str], dict[str, Any]] = {}
    for path in (PROFILE, INTENT):
        for index, edge in enumerate(documents[path]["requested_edges"]):
            if edge["contract_id"] != CONTRACT:
                continue
            key = (edge["caller_function_id"], edge["operation_id"],
                   edge["target_provider_id"])
            item = edges.setdefault(key, {
                "caller_function_id": key[0], "operation_id": key[1],
                "target_provider_id": key[2], "declarations": [],
            })
            item["declarations"].append({
                "path": path, "json_pointer": f"/requested_edges/{index}",
            })
    expected = {
        (f"rumi_ai_gateway_pack.ai-gateway.{name}", f"{PREFIX}.{operation}")
        for name, operation in (("generate", "generate"), ("stream", "stream"),
                                ("text-generate", "generate"),
                                ("messages-generate", "generate"))
    }
    if ({key[:2] for key in edges} != expected or len(edges) != 4
            or any(len(item["declarations"]) != 2 for item in edges.values())):
        raise ValueError("expected four original Gateway edges in both profiles")
    tree = ast.parse(sources[GATEWAY], filename=GATEWAY)
    evidence = [_slice(GATEWAY, sources[GATEWAY], _symbol(tree, name), name)[1]
                for name in (*SYMBOLS, "_invoke")]
    call_sites = []
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "_tool_intents"):
            _, record = _slice(GATEWAY, sources[GATEWAY], node, node.func.id)
            expression = next((keyword.value for keyword in node.keywords
                               if keyword.arg == "streaming"), None)
            record["streaming_expression"] = (
                ast.get_source_segment(sources[GATEWAY].decode(), expression)
                if expression is not None else None
            )
            call_sites.append(record)
    wrappers = []
    for name, (filename, factory) in WRAPPERS.items():
        path = f"{ECOSYSTEM}/rumi_ai_gateway_pack/runtime/{filename}"
        content = sources[path]
        wrapper_tree = ast.parse(content, filename=path)
        identity = _symbol(wrapper_tree, "FUNCTION_ID")
        caller = f"rumi_ai_gateway_pack.ai-gateway.{name}"
        if (not isinstance(identity, ast.Assign)
                or not isinstance(identity.value, ast.Constant)
                or identity.value.value != caller):
            raise ValueError("wrapper identity differs from original caller edge")
        calls = []
        for node in ast.walk(_symbol(wrapper_tree, factory)):
            if isinstance(node, ast.Call):
                target = ast.get_source_segment(content.decode(), node.func)
                if target in {"gateway.create_generate_operation", "generate"}:
                    calls.append(_slice(path, content, node, target)[1])
        if sorted(item["symbol"] for item in calls) != [
            "gateway.create_generate_operation", "generate",
        ]:
            raise ValueError("expected original wrapper delegation calls")
        wrappers.append({
            "caller_function_id": caller, "migrated": False,
            "definitions": [_slice(path, content, _symbol(wrapper_tree, symbol),
                                    symbol)[1]
                            for symbol in ("FUNCTION_ID", factory,
                                           "HOST_PROVIDER_FACTORY")],
            "gateway_delegation_calls": sorted(
                calls, key=lambda item: item["source_start_line"],
            ),
        })
    return {
        "schema": "io.tobkiri.gateway-tool-caller-inventory.v1",
        "contract_id": CONTRACT,
        "sources": [_record(path, value) for path, value in sources.items()],
        "operations": [{"operation_id": name, "declarations": refs}
                       for name, refs in declarations.items()],
        "caller_edges": list(edges.values()), "gateway_evidence": evidence,
        "gateway_tool_intent_call_sites": sorted(
            call_sites, key=lambda item: item["source_start_line"],
        ),
        "wrapper_evidence": wrappers,
        "exported_helper_operations": ["generate-intents", "stream-intents",
                                       "stream-event-intents"],
        "not_migrated": ["_invoke", "text-generate wrapper",
                         "messages-generate wrapper", "Host provider capture"],
        "notes": [
            "Four original caller edges are evidence, not four exported identities.",
            "Only the original normalization callers are selected source slices.",
            "No model selection, provider generation, retry, or failover is migrated.",
            "All imported Core errors are terminal and preserve typed error custody.",
            "Transport and malformed successful replies are terminal, without replay.",
            "Codec and canonical Core/bridge WIT are hash-bound, not copied.",
        ],
    }


def _prepared_files() -> tuple[dict[str, bytes], dict[str, Any]]:
    paths = (
        GATEWAY, DISPATCH,
        *(f"{BRIDGE_PACK}/{name}.v4.json"
          for name in ("contracts", "executables", "pack")),
        PROFILE, INTENT,
        *(f"{ECOSYSTEM}/rumi_ai_gateway_pack/runtime/{filename}"
          for filename, _ in WRAPPERS.values()),
        *CODEC_PATHS, CORE_WIT, BRIDGE_WIT,
    )
    sources = {path: _capture(path) for path in paths}
    module, provenance = _extract(sources)
    inventory = _json_bytes(_inventory(sources))
    provenance["inventory"] = _record("inventory.json", inventory)
    provenance["transport_dependencies"] = [
        _record(path, sources[path]) for path in (*CODEC_PATHS, CORE_WIT, BRIDGE_WIT)
    ]
    provenance["protocol"] = "ordered-finite-json-v2"
    return {
        "original_gateway_tool_caller.py": module,
        "inventory.json": inventory, "provenance.json": _json_bytes(provenance),
    }, provenance


def prepare(output: Path) -> dict[str, Any]:
    """Write deterministic slices with no link-following, compiler, or runtime."""
    files, provenance = _prepared_files()
    descriptor = None
    try:
        descriptor = _directory(Path(output), create=True)
        # Preflight every existing target before changing any file.
        for name in files:
            try:
                info = os.stat(name, dir_fd=descriptor, follow_symlinks=False)
            except FileNotFoundError:
                continue
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise ValueError(f"output must be an unlinked regular file: {name}")
        for name, content in files.items():
            target = os.open(
                name, os.O_WRONLY | os.O_CREAT | os.O_NOFOLLOW | os.O_NONBLOCK,
                0o644, dir_fd=descriptor,
            )
            try:
                info = os.fstat(target)
                if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                    raise ValueError(f"unsafe output target: {name}")
                os.ftruncate(target, 0)
                remaining = memoryview(content)
                while remaining:
                    written = os.write(target, remaining)
                    if not written:
                        raise ValueError(f"incomplete output write: {name}")
                    remaining = remaining[written:]
            finally:
                os.close(target)
    except OSError as error:
        raise ValueError("output must have only real directory ancestors") from error
    finally:
        if descriptor is not None:
            os.close(descriptor)
    return provenance


def verify(output: Path) -> dict[str, Any]:
    """Verify all captured source and transport evidence without rewriting it."""
    files, provenance = _prepared_files()
    for name, expected in files.items():
        if bounded_read(Path(output) / name) != expected:
            raise ValueError(f"extraction does not match original source: {name}")
    return provenance


def main() -> None:
    """Prepare or verify source-only evidence, never a component or deployment."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    result = verify(args.output) if args.verify else prepare(args.output)
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
