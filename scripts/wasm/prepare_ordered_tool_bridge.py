"""Extract the original pure Python tool bridge without executing or translating it.

Only complete, byte-identical source slices and their stdlib imports enter the
module. Host-provider capture, registration, and import plumbing stay outside.
This preparation step does not build, run, or enable a component.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
ECOSYSTEM = "tobkiri_runtime/ecosystem"
BRIDGE = f"{ECOSYSTEM}/rumi_ai_tool_bridge_pack/runtime/bridge.py"
DISPATCH = "tobkiri_runtime/core_runtime/global_contract_dispatch.py"
GATEWAY = f"{ECOSYSTEM}/rumi_ai_gateway_pack/runtime/gateway.py"
BRIDGE_PACK = f"{ECOSYSTEM}/rumi_ai_tool_bridge_pack"
PROFILE = f"{ECOSYSTEM}/defaultspack/v4/defaults.profile.v5.json"
INTENT = f"{ECOSYSTEM}/defaultspack/v4/defaults.profile.intent.v1.json"
CONTRACT = "tobkiri.service.ai.tool_intent.normalize.v1"
HEADER = (
    b"# Generated by scripts/wasm/prepare_ordered_tool_bridge.py.\n"
    b"# Source slices below are verbatim; see provenance.json.\n\n"
)
SYMBOLS = ("_TOOL_NAME", "create_tool_intent_operation", "_normalize", "_invalid")
IMPORTS = (
    ("__future__", ("annotations",)),
    (None, ("json",)),
    (None, ("re",)),
    ("typing", ("Any", "Callable", "Mapping")),
)


def _sha256(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode("utf-8")


def _capture(path: str) -> bytes:
    source = ROOT / path
    if source.is_symlink() or not source.is_file():
        raise ValueError(f"source must be a regular file: {path}")
    return source.read_bytes()


def _source_record(path: str, content: bytes) -> dict[str, Any]:
    return {"path": path, "sha256": _sha256(content), "bytes": len(content)}


def _symbol(tree: ast.Module, name: str) -> ast.stmt:
    matches = [
        node for node in tree.body
        if (
            isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name
        ) or (
            isinstance(node, ast.Assign)
            and any(isinstance(target, ast.Name) and target.id == name
                    for target in node.targets)
        )
    ]
    if len(matches) != 1:
        raise ValueError(f"expected exactly one source definition of {name}")
    return matches[0]


def _source_slice(
    path: str, content: bytes, node: ast.AST, label: str,
) -> tuple[bytes, dict[str, Any]]:
    start = node.lineno
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.decorator_list:
        start = min(start, *(item.lineno for item in node.decorator_list))
    end = node.end_lineno
    if end is None:
        raise ValueError(f"missing source extent for {label}")
    lines = content.splitlines(keepends=True)
    byte_start = sum(map(len, lines[:start - 1]))
    byte_end = sum(map(len, lines[:end]))
    value = content[byte_start:byte_end]
    return value, {
        "symbol": label,
        "source_path": path,
        "source_start_line": start,
        "source_end_line": end,
        "source_start_byte": byte_start,
        "source_end_byte": byte_end,
        "sha256": _sha256(value),
    }


def _extract_module() -> tuple[bytes, dict[str, Any]]:
    sources = {path: _capture(path) for path in (BRIDGE, DISPATCH)}
    trees = {path: ast.parse(content, filename=path)
             for path, content in sources.items()}
    selected: list[tuple[str, ast.stmt, str]] = []
    for module, names in IMPORTS:
        matches = [
            node for node in trees[BRIDGE].body
            if isinstance(node, (ast.Import, ast.ImportFrom))
            and (node.module if isinstance(node, ast.ImportFrom) else None) == module
            and (not isinstance(node, ast.ImportFrom) or node.level == 0)
            and tuple(alias.name for alias in node.names) == names
            and not any(alias.asname for alias in node.names)
        ]
        if len(matches) != 1:
            raise ValueError(f"expected exactly one stdlib import: {module}, {names}")
        selected.append((BRIDGE, matches[0], f"import:{module or names[0]}"))
    selected.append((
        DISPATCH, _symbol(trees[DISPATCH], "GlobalContractInvocationError"),
        "GlobalContractInvocationError",
    ))
    selected.extend((BRIDGE, _symbol(trees[BRIDGE], name), name) for name in SYMBOLS)
    output = bytearray(HEADER)
    slices = []
    for index, (path, node, label) in enumerate(selected):
        content, record = _source_slice(path, sources[path], node, label)
        record["output_start_byte"] = len(output)
        record["output_start_line"] = output.count(b"\n") + 1
        output.extend(content)
        record["output_end_byte"] = len(output)
        record["output_end_line"] = output.count(b"\n") + (not content.endswith(b"\n"))
        if index + 1 < len(selected):
            output.extend(b"\n\n")
        elif not content.endswith(b"\n"):
            output.extend(b"\n")
        slices.append(record)
    module_bytes = bytes(output)
    # Parsing is structural validation, not execution of the extracted module.
    ast.parse(module_bytes, filename="original_bridge.py")
    return module_bytes, {
        "schema": "io.tobkiri.python-source-extraction.v1",
        "generator": "scripts/wasm/prepare_ordered_tool_bridge.py",
        "extraction": "verbatim-complete-source-lines",
        "line_numbers": "one-based-inclusive",
        "byte_offsets": "zero-based-half-open",
        "sources": [_source_record(path, content)
                    for path, content in sources.items()],
        "slices": slices,
        "output": _source_record("original_bridge.py", module_bytes),
        "build_performed": False,
        "production_enabled": False,
    }


def _inventory() -> dict[str, Any]:
    paths = (
        f"{BRIDGE_PACK}/contracts.v4.json",
        f"{BRIDGE_PACK}/executables.v4.json",
        f"{BRIDGE_PACK}/pack.v4.json",
        PROFILE, INTENT, GATEWAY,
    )
    sources = {path: _capture(path) for path in paths}
    documents = {path: json.loads(content) for path, content in sources.items()
                 if path.endswith(".json")}
    declarations: dict[str, list[dict[str, Any]]] = {}
    for path, document in documents.items():
        if path.endswith("/contracts.v4.json"):
            for index, contract in enumerate(document["contracts"]):
                if contract["contract_id"] != CONTRACT:
                    continue
                for position, operation in enumerate(contract["operations"]):
                    declarations.setdefault(operation["operation_id"], []).append({
                        "path": path,
                        "json_pointer": f"/contracts/{index}/operations/{position}",
                    })
        elif path.endswith("/executables.v4.json"):
            for index, variant in enumerate(document["variants"]):
                for position, operation in enumerate(variant["operations"]):
                    if operation["contract_id"] == CONTRACT:
                        declarations.setdefault(operation["operation_id"], []).append({
                            "path": path,
                            "json_pointer": f"/variants/{index}/operations/{position}",
                        })
        elif path.endswith("/pack.v4.json"):
            for index, operation in enumerate(document["operation_catalog"]):
                if operation["contract_reference"] == CONTRACT:
                    declarations.setdefault(operation["operation_id"], []).append({
                        "path": path, "json_pointer": f"/operation_catalog/{index}",
                    })
    if len(declarations) != 3 or any(len(refs) != 3 for refs in declarations.values()):
        raise ValueError("expected all three bridge operations in all three manifests")
    edges: dict[tuple[str, str, str], dict[str, Any]] = {}
    for path in (PROFILE, INTENT):
        for index, edge in enumerate(documents[path]["requested_edges"]):
            if edge["contract_id"] != CONTRACT:
                continue
            key = (edge["caller_function_id"], edge["operation_id"],
                   edge["target_provider_id"])
            record = edges.setdefault(key, {
                "caller_function_id": key[0], "operation_id": key[1],
                "target_provider_id": key[2], "declarations": [],
            })
            record["declarations"].append({
                "path": path, "json_pointer": f"/requested_edges/{index}",
            })
    if len(edges) != 4 or any(
        len(edge["declarations"]) != 2 for edge in edges.values()
    ):
        raise ValueError("expected all four caller edges in both original profiles")
    if any(edge["operation_id"] not in declarations for edge in edges.values()):
        raise ValueError("caller edge refers to an undeclared bridge operation")
    tree = ast.parse(sources[GATEWAY], filename=GATEWAY)
    gateway_evidence = []
    for name in (
        "TOOL_BRIDGE_CONTRACT", "TOOL_BRIDGE_GENERATE_OPERATION",
        "TOOL_BRIDGE_STREAM_OPERATION", "TOOL_BRIDGE_OPERATION", "_tool_intents",
        "_attach_stream_tool_intents",
    ):
        _, record = _source_slice(GATEWAY, sources[GATEWAY], _symbol(tree, name), name)
        gateway_evidence.append(record)
    call_sites = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            if node.func.id == "_tool_intents":
                _, record = _source_slice(GATEWAY, sources[GATEWAY], node, node.func.id)
                streaming = next((keyword.value for keyword in node.keywords
                                  if keyword.arg == "streaming"), None)
                record["streaming_expression"] = (
                    ast.get_source_segment(sources[GATEWAY].decode("utf-8"), streaming)
                    if streaming is not None else None
                )
                call_sites.append(record)
    return {
        "schema": "io.tobkiri.python-tool-bridge-inventory.v1",
        "contract_id": CONTRACT,
        "sources": [_source_record(path, content)
                    for path, content in sources.items()],
        "operations": [{"operation_id": operation, "declarations": refs}
                       for operation, refs in declarations.items()],
        "caller_edges": list(edges.values()),
        "gateway_evidence": gateway_evidence,
        "gateway_tool_intent_call_sites": sorted(
            call_sites, key=lambda record: record["source_start_line"],
        ),
        "notes": [
            "The base operation is declared but has no caller edge in these profiles.",
            "Gateway stream calls select .stream; other listed edges select .generate.",
            "The original host factory invokes the pure callable as normalize.",
            "No profile, manifest, host capture, or runtime selection is modified.",
        ],
    }


def _prepared_files() -> tuple[dict[str, bytes], dict[str, Any]]:
    module, provenance = _extract_module()
    inventory = _json_bytes(_inventory())
    provenance["inventory"] = _source_record("inventory.json", inventory)
    return {
        "original_bridge.py": module,
        "inventory.json": inventory,
        "provenance.json": _json_bytes(provenance),
    }, provenance


def prepare(output: Path) -> dict[str, Any]:
    """Write byte-identical slices and deterministic evidence to an output directory."""
    output = Path(output)
    files, provenance = _prepared_files()
    if output.is_symlink() or (output.exists() and not output.is_dir()):
        raise ValueError("output must be a directory, not a symlink or file")
    for name in files:
        target = output / name
        if target.is_symlink() or (target.exists() and not target.is_file()):
            raise ValueError(f"output must be a regular file: {target}")
    output.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (output / name).write_bytes(content)
    return provenance


def verify(output: Path) -> dict[str, Any]:
    """Reject stale or modified extraction/evidence against current original sources."""
    files, provenance = _prepared_files()
    for name, expected in files.items():
        target = Path(output) / name
        if (target.is_symlink() or not target.is_file()
                or target.read_bytes() != expected):
            raise ValueError(f"extraction does not match original source: {name}")
    return provenance


def main() -> None:
    """Prepare or verify source-only artifacts without a compiler or runtime."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="output directory")
    parser.add_argument("--verify", action="store_true", help="verify without writing")
    args = parser.parse_args()
    result = verify(args.output) if args.verify else prepare(args.output)
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
