"""Capture the original pure Setup decision/response methods, without effects.

No source import, compiler, guest, activation, or authority store is executed.
The selected complete lines retain their original bytes and indentation.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
from pathlib import Path

from prepare_gateway_tool_caller import (
    ROOT, _directory, _json_bytes, _record, _slice, _symbol, bounded_read,
)
from stage_gateway_finalizer import _write

SOURCE = (
    "tobkiri_runtime/ecosystem/defaultspack/defaultspack/"
    "profile_runtime_composition.py"
)
PORT = "tobkiri_runtime/core_runtime/profile_runtime_port.py"
METHODS = (
    "_confirmation", "bootstrap_confirmation", "profile_confirmation",
    "setup_activation_decision", "setup_activation_success",
    "setup_activation_failure", "retired_setup_response",
)
PACK = ROOT / "packs/local.harness-setup-python"
INTERFACE = "local:harness-setup-python/setup@1.0.0"
DEPENDENCIES = {
    "python/app.py": "packs/local.harness-setup-python/python/app.py",
    "python/setup_adapter.py":
        "packs/local.harness-setup-python/python/setup_adapter.py",
    "python/ordered_json.py":
        "packs/local.ai-tool-bridge-ordered-python/ordered_json.py",
    "python/ordered_json_v2.py":
        "packs/local.ai-tool-bridge-ordered-python/ordered_json_v2.py",
    **{f"python/tobkiri_protocol/{name}.py":
       f"tobkiri_runtime/tobkiri_protocol/{name}.py"
       for name in ("__init__", "canonical", "errors", "ids")},
    "wit/pack.wit": "packs/local.harness-setup-python/wit/pack.wit",
    "wit/deps/tobkiri-core/core.wit": "crates/tobkiri-wit/wit/core/core.wit",
}


def captured() -> dict[str, bytes]:
    """Reconstruct verbatim source and provenance from bounded no-link reads."""
    sources = {name: bounded_read(ROOT / name) for name in (SOURCE, PORT)}
    tree = ast.parse(sources[SOURCE], filename=SOURCE)
    runtime = _symbol(tree, "DefaultspackProfileRuntime")
    if not isinstance(runtime, ast.ClassDef):
        raise ValueError("original Profile composition must remain a class")
    port_tree = ast.parse(sources[PORT], filename=PORT)
    decision = _symbol(port_tree, "SetupActivationDecision")
    decision_bytes, record = _slice(
        PORT, sources[PORT], decision, "SetupActivationDecision",
    )
    header = (
        b"# Generated by scripts/wasm/prepare_harness_setup.py.\n"
        b"# Verbatim original definitions; no Host authority or effects.\n\n"
        b"from __future__ import annotations\n"
        b"from dataclasses import dataclass\n"
        b"from typing import Any, Mapping\n\n"
        b"from tobkiri_protocol.canonical import canonical_digest\n\n"
    )
    module = header + decision_bytes + b"\n\n"
    # The new container is packaging, not a rewrite of an original method.
    module += b"class DefaultspackProfileRuntime:\n"
    records = [record]
    for name in METHODS:
        matches = [node for node in runtime.body
                   if isinstance(node, ast.FunctionDef) and node.name == name]
        if len(matches) != 1:
            raise ValueError(f"one complete original Setup method required: {name}")
        content, record = _slice(SOURCE, sources[SOURCE], matches[0], name)
        module += content
        if name != METHODS[-1]:
            module += b"\n"
        records.append(record)
    compile(module, "original_setup.py", "exec")  # Syntax only; never execute it.
    provenance = {
        "format": "tobkiri.harness-setup-source/1",
        "scope": "pure confirmation, decision and response projection only",
        "sources": [_record(name, data) for name, data in sources.items()],
        "definitions": records,
        "generated_module": _record("original_setup.py", module),
        "transport_dependencies": [
            _record(path, bounded_read(ROOT / path))
            for path in DEPENDENCIES.values()
        ],
        "method_rewrites": [],
        "production_enabled": False,
        "wasm_execution_performed": False,
        "native_setup_integration": False,
    }
    return {"original_setup.py": module,
            "provenance.json": _json_bytes(provenance)}


def verify() -> dict[str, bytes]:
    """Reject stale extraction or changed transport before staging a build."""
    expected = captured()
    for name, content in expected.items():
        if bounded_read(PACK / "python" / name) != content:
            raise ValueError(f"Setup extraction differs from original source: {name}")
    return expected


def _publish(output: Path, files: dict[str, bytes]) -> None:
    """Write fresh private output through no-follow directory descriptors.

    The existing parent is trusted. Existing destinations are never replaced;
    an incomplete fresh directory is retained if publication fails.
    """
    if ".." in output.parts or any(c in str(output) for c in "\\:\0"):
        raise ValueError("fresh normalized output required")
    output = output.absolute()
    parent = _directory(output.parent)
    descriptor = None
    try:
        os.mkdir(output.name, mode=0o700, dir_fd=parent)
        descriptor = os.open(
            output.name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
            dir_fd=parent,
        )
        for name, data in files.items():
            _write(descriptor, name, data)
        actual, opened = os.stat(
            output.name, dir_fd=parent, follow_symlinks=False,
        ), os.fstat(descriptor)
        if (actual.st_dev, actual.st_ino) != (opened.st_dev, opened.st_ino):
            raise ValueError("output directory changed during publication")
    finally:
        if descriptor is not None:
            os.close(descriptor)
        os.close(parent)


def stage(output: Path) -> dict:
    """Stage a hash-bound SDK plan; never build or activate this candidate."""
    generated = verify()
    files = {name: bounded_read(ROOT / path)
             for name, path in DEPENDENCIES.items()}
    files["python/original_setup.py"] = generated["original_setup.py"]
    plan = {
        "format": "tobkiri.python-build/3", "stub_wasi": True,
        "wit": "wit/pack.wit", "world": "pack", "entrypoint": "app",
        "sources": [
            {"source": name,
             "destination": name.removeprefix("python/"),
             "sha256": _record(name, data)["sha256"]}
            for name, data in sorted(files.items())
        ],
        "outer_exports": ["tobkiri:core/lifecycle@1.0.0", INTERFACE],
        "allowed_imports": [f"tobkiri:core/{name}@1.0.0" for name in
                            ("types", "flow", "clock", "random", "audit")],
    }
    files["plan.json"] = _json_bytes(plan)
    files["source-stage.json"] = generated["provenance.json"]
    # Capture again before publication to detect a source change during staging.
    if verify() != generated or any(
        files[name] != bounded_read(ROOT / path)
        for name, path in DEPENDENCIES.items()
    ):
        raise ValueError("Setup source changed during staging")
    _publish(output, files)
    return plan


def main() -> None:
    """Prepare a fresh extraction, verify it, or stage source-only build input."""
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--output", type=Path)
    mode.add_argument("--stage", type=Path)
    mode.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    if args.stage is not None:
        stage(args.stage)
    elif args.output is not None:
        _publish(args.output, captured())
    else:
        verify()
    print(json.dumps({"source_verified": True, "build_performed": False,
                      "production_enabled": False}))


if __name__ == "__main__":
    main()
