import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

const json = (path: string) => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));

test('opt-in native host selects only its bundled capability and closed CSP', () => {
  const config = json('../../../src-tauri/tauri.core-host.conf.json');
  const capability = json('../../../src-tauri/capabilities/core-host.json');
  assert.deepEqual(config.app.security.capabilities, ['core-host']);
  assert.equal(config.app.withGlobalTauri, false);
  assert.deepEqual(capability.windows, ['core-host']);
  assert.equal(capability.local, true);
  assert.equal(capability.remote, undefined);
  const csp = config.app.security.csp as string;
  assert.ok(csp.includes("script-src 'self'"));
  assert.ok(csp.includes("object-src 'none'"));
  assert.ok(csp.includes('frame-src tobkiri-pack:'));
  assert.ok(!csp.includes('unsafe-inline'));
  assert.ok(!csp.includes('127.0.0.1'));
  assert.ok(!csp.includes('localhost:*'));
  const host = readFileSync(new URL('../../../src-tauri/src/core_host.rs', import.meta.url), 'utf8');
  const manifest = readFileSync(new URL('../../../src-tauri/build.rs', import.meta.url), 'utf8');
  const commandsSource = readFileSync(new URL('../../../src-tauri/src/core_host_commands.rs', import.meta.url), 'utf8');
  const commands = [...commandsSource.matchAll(/"([a-z_]+)"/g)].map((match) => match[1]).sort();
  const handlers = host.match(/invoke_handler\(tauri::generate_handler!\[([\s\S]*?)\]\)/)?.[1].split(',').map((value) => value.trim()).filter(Boolean).sort();
  const capabilities = (capability.permissions as string[]).filter((permission) => !permission.startsWith('core:')).map((permission) => permission.slice('allow-'.length).replaceAll('-', '_')).sort();
  const expectedCommands = [
    'core_start_profile',
    'core_stop_session',
    'core_host_output_ack',
    'core_terminal_reply',
    'pack_ui_invoke',
    'pack_ui_register',
    'pack_ui_cancel',
    'pack_ui_ack',
    'pack_ui_detach',
    'pack_ui_stream_pull',
    'pack_ui_stream_cancel',
  ].sort();
  assert.equal(commands.length, 11);
  assert.equal(new Set(commands).size, 11);
  assert.deepEqual(commands, expectedCommands);
  assert.deepEqual(handlers, expectedCommands);
  assert.deepEqual(capabilities, expectedCommands);
  assert.deepEqual([...(capability.permissions as string[])].sort(), [
    'core:event:allow-listen',
    'core:event:allow-unlisten',
    ...expectedCommands.map((command) => `allow-${command.replaceAll('_', '-')}`),
  ].sort());
  const coreBuild = manifest.slice(manifest.indexOf('if cfg!(feature = "core-host")'), manifest.indexOf('println!("cargo:rerun-if-changed=splash/index.html")'));
  assert.ok(coreBuild.includes('build_tauri_manifest(core_host_commands::CORE_HOST_COMMANDS)'));
  assert.ok(coreBuild.includes('bind_macos_artifact_policy()'));
  assert.ok(coreBuild.includes('CoreHostManifestScope::enter()'));
  assert.ok(manifest.includes('attributes.capabilities_path_pattern("capabilities/core-host.json")'));
  assert.ok(!coreBuild.includes('build_legacy_tauri_manifest'));
  assert.ok(!coreBuild.includes('stage_runtime_bundle()'));
  assert.ok(!coreBuild.includes('stage_local_development_authority()'));
  for (const permission of capability.permissions as string[]) {
    if (permission.startsWith('core:')) continue;
    const command = permission.slice('allow-'.length).replaceAll('-', '_');
    assert.ok(commands.includes(command), command);
    assert.ok(host.includes(`fn ${command}(`), command);
    const definition = readFileSync(new URL(`../../../src-tauri/permissions/autogenerated/${command}.toml`, import.meta.url), 'utf8');
    const allowed = definition.match(/commands\.allow\s*=\s*\[([^\]]*)\]/)?.[1];
    assert.ok(allowed, permission);
    assert.deepEqual([...allowed.matchAll(/"([^"]+)"/g)].map((match) => match[1]), [command]);
    assert.ok(definition.includes(`identifier = "${permission}"`), permission);
  }
  assert.ok(host.includes('Content-Security-Policy'));
  assert.ok(host.includes('PACK_UI_CSP'));
  assert.ok(host.includes('X-Content-Type-Options'));
});

test('native callbacks use the tested close/reopen/finite shutdown and risk contracts', () => {
  const host = readFileSync(new URL('../../../src-tauri/src/core_host.rs', import.meta.url), 'utf8');
  const review = readFileSync(new URL('../../../src-tauri/src/native_plan_review.rs', import.meta.url), 'utf8');
  assert.ok(host.includes('tauri_plugin_single_instance::init'));
  const coreOpen = host.indexOf('core::Core::open(');
  const wrapper = host.indexOf('LauncherCore::from_shared_core_with_tickets(');
  assert.ok(coreOpen >= 0, 'the actual runtime must be opened by native composition');
  assert.equal([...host.matchAll(/\bCore::open\(/g)].length, 1, 'one actual Core is opened');
  assert.ok(host.indexOf('tauri_plugin_single_instance::init') < coreOpen);
  assert.ok(wrapper > coreOpen, 'the frontend wraps the existing runtime after opening it');
  assert.ok(host.includes('WindowEvent::CloseRequested'));
  assert.ok(host.includes('preserve_primary_close'));
  assert.ok(host.includes('restore_primary'));
  assert.ok(host.includes('observe_shutdown(receiver, crate::shutdown_budget::RUNTIME_WATCHDOG)'));
  assert.ok(host.includes('startup_ui_embedding(&request.slot'));
  assert.ok(host.includes('trusted_review(&prompt)'));
  assert.ok(host.includes('review.dangerous'));
  assert.ok(review.includes('NSAlertStyle::Critical'));
  // These source-wiring checks and mocked lifecycle execution are not native
  // evidence of iframe origin, window events or AppKit appearance.
});

